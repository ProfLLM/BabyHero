import AVFoundation
import BabyHeroCore
import Combine
import SwiftUI

@MainActor
final class AppModel: ObservableObject {
    enum State: Equatable {
        case idle, requesting, listening, paused
    }

    struct Issue: Identifiable {
        let id = UUID()
        let title: String
        let message: String
        var offersSettings = false
    }

    @Published private(set) var state: State = .idle
    @Published private(set) var snapshot: AnalysisSnapshot?
    @Published private(set) var selectedTone: Tone?
    @Published private(set) var pauseMessage: String?
    @Published var issue: Issue?
    @Published private(set) var isPreview = false
    private let capture = AudioCapture()
    private var requestToken = UUID()
    private var captureOperation = 0
    private var startup: Task<Void, Never>?
    private let observers = NotificationSubscriptions()
    private var isInBackground = false
    private var isSceneActive = true
    private var permissionReady = false
    private var startedAt: Date?
    private var watchdog: Task<Void, Never>?

    init(preview: String? = nil) {
        if let preview {
            installPreview(preview)
            return
        }
        let center = NotificationCenter.default
        observers.append(center.addObserver(forName: AVAudioSession.interruptionNotification, object: nil, queue: .main) { [weak self] notification in
            let type = notification.userInfo?[AVAudioSessionInterruptionTypeKey] as? UInt
            guard type == AVAudioSession.InterruptionType.began.rawValue else { return }
            Task { @MainActor [weak self] in self?.pause("Listening paused by another app. Tap to start a fresh reading.") }
        })
        observers.append(center.addObserver(forName: AVAudioSession.routeChangeNotification, object: nil, queue: .main) { [weak self] notification in
            let raw = notification.userInfo?[AVAudioSessionRouteChangeReasonKey] as? UInt
            // Ignore category / preferred-input notifications generated by our own setup.
            let reasons: [UInt] = [AVAudioSession.RouteChangeReason.newDeviceAvailable.rawValue,
                                   AVAudioSession.RouteChangeReason.oldDeviceUnavailable.rawValue,
                                   AVAudioSession.RouteChangeReason.noSuitableRouteForCategory.rawValue,
                                   AVAudioSession.RouteChangeReason.routeConfigurationChange.rawValue]
            guard let raw, reasons.contains(raw) else { return }
            Task { @MainActor [weak self] in self?.pause("The microphone connection changed. Start again to reset the comparison.") }
        })
        observers.append(center.addObserver(forName: AVAudioSession.mediaServicesWereResetNotification, object: nil, queue: .main) { [weak self] _ in
            Task { @MainActor [weak self] in self?.pause("The audio system restarted. Tap to start a fresh reading.") }
        })
    }

    deinit {
        watchdog?.cancel()
        startup?.cancel()
    }

    var isListening: Bool { state == .listening }

    func start() {
        guard state != .requesting, state != .listening else { return }
        guard !isPreview else { installPreview("listening"); return }
        issue = nil
        pauseMessage = nil
        state = .requesting
        permissionReady = false
        let token = UUID()
        requestToken = token
        AVAudioApplication.requestRecordPermission { [weak self] granted in
            Task { @MainActor [weak self] in
                guard let self, self.requestToken == token, self.state == .requesting,
                      !self.isInBackground else { return }
                guard granted else {
                    self.state = .idle
                    self.issue = Issue(title: "Microphone access is off", message: "Allow Microphone in Settings to look for high-pitched tones. Audio is processed on your iPhone and never saved.", offersSettings: true)
                    return
                }
                self.permissionReady = true
                if self.isSceneActive { self.beginCapture() }
            }
        }
    }

    private func beginCapture() {
        permissionReady = false
        snapshot = nil
        selectedTone = nil
        captureOperation += 1
        let operation = captureOperation
        let token = requestToken
        startup = Task { [weak self] in
            guard let self else { return }
            do {
                try await self.capture.start(operation: operation) { [weak self] reading in
                    guard let self, self.requestToken == token, self.captureOperation == operation,
                          self.state == .listening else { return }
                    self.snapshot = reading
                    self.startedAt = Date()
                }
                guard !Task.isCancelled, self.requestToken == token, !self.isInBackground else { return }
                self.startup = nil
                self.state = .listening
                self.startedAt = Date()
                self.watchdog = Task { [weak self] in
                    while !Task.isCancelled {
                        try? await Task.sleep(for: .seconds(2))
                        guard !Task.isCancelled, let self, self.isListening else { return }
                        if let last = self.startedAt, Date().timeIntervalSince(last) > 5 {
                            self.pause("The microphone stopped sending audio. Tap to try again.")
                            self.issue = Issue(title: "No microphone signal", message: "The audio input stopped responding. Check your microphone connection and start again.")
                            return
                        }
                    }
                }
            } catch {
                guard self.requestToken == token, !Task.isCancelled else { return }
                self.startup = nil
                self.state = .idle
                self.issue = Issue(title: "Couldn’t start listening", message: error.localizedDescription)
            }
        }
    }

    func stop() {
        requestToken = UUID()
        permissionReady = false
        startup?.cancel()
        startup = nil
        watchdog?.cancel()
        watchdog = nil
        captureOperation += 1
        let operation = captureOperation
        if !isPreview { Task { await capture.stop(operation: operation) } }
        state = .idle
        snapshot = nil
        selectedTone = nil
        pauseMessage = nil
    }

    func pause(_ message: String) {
        guard state == .listening || state == .requesting else { return }
        stop()
        pauseMessage = message
        state = .paused
    }

    func sceneChanged(_ phase: ScenePhase) {
        isSceneActive = phase == .active
        if phase == .active { isInBackground = false }
        if phase == .background { isInBackground = true }
        // The permission dialog temporarily makes the scene inactive. Wait for its
        // result; a real background transition still cancels a pending request.
        if phase == .background || (phase == .inactive && (state == .listening || startup != nil)) {
            pause("Listening paused while you were away. Tap to start a fresh reading.")
        }
        if phase == .active && state == .requesting && permissionReady { beginCapture() }
    }

    func select(_ tone: Tone) {
        guard isListening else { return }
        selectedTone = tone
        let operation = captureOperation
        Task { await capture.select(frequency: tone.frequency, operation: operation) }
        if isPreview { installPreview("finder", following: tone) }
    }

    func backToSounds() {
        selectedTone = nil
        let operation = captureOperation
        Task { await capture.select(frequency: nil, operation: operation) }
    }

    // Explicit, launch-only fixtures: no demo audio is ever mixed with live capture.
    private func installPreview(_ name: String, following: Tone? = nil) {
        isPreview = true
        let firstTone = Tone(id: 1, frequency: 15_420, level: -39, prominence: 22)
        let tone = following ?? firstTone
        state = name == "idle" ? .idle : .listening
        if name == "denied" {
            state = .idle
            issue = Issue(title: "Microphone access is off", message: "Allow Microphone in Settings to look for high-pitched tones. Audio is processed on your iPhone and never saved.", offersSettings: true)
        }
        if name == "paused" {
            state = .paused
            pauseMessage = "The microphone connection changed. Start again to reset the comparison."
        }
        let history = (0..<65).map { index in
            SignalPoint(time: Double(index) * 0.17, level: tone.level - 25 + Double(index) * 0.38 + sin(Double(index) * 0.4) * 2)
        }
        let tracking = TrackingReading(frequency: tone.frequency, level: name == "lost" ? nil : tone.level,
                                       trend: name == "lost" ? .lost : .stronger, history: history)
        snapshot = AnalysisSnapshot(elapsed: 11, upperFrequency: 20_000,
                                    tones: name == "quiet" ? [] : [firstTone, Tone(id: 2, frequency: 11_820, level: -52, prominence: 18)],
                                    tracking: ["finder", "lost"].contains(name) ? tracking : nil)
        selectedTone = ["finder", "lost"].contains(name) ? tone : nil
    }
}

/// Tokens are registered on the main actor. Once the owner is released, cleanup
/// can run on any thread; NotificationCenter supports thread-safe removal.
private final class NotificationSubscriptions: @unchecked Sendable {
    private var tokens: [NSObjectProtocol] = []
    func append(_ token: NSObjectProtocol) { tokens.append(token) }
    deinit { tokens.forEach { NotificationCenter.default.removeObserver($0) } }
}
